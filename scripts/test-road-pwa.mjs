import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {startServer} from './serve.mjs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=await startServer(undefined,4193);
const browser=await chromium.launch({headless:true,channel:'msedge'});
try{
 const context=await browser.newContext({viewport:{width:390,height:844}});
 await context.addInitScript(()=>{window.tapCount=0;navigator.vibrate=()=>{window.tapCount++;return true;}});
 const page=await context.newPage();
 await page.goto('http://127.0.0.1:4193/customer-account',{waitUntil:'load'});
 await page.evaluate(()=>navigator.serviceWorker.ready);
 await page.waitForFunction(()=>navigator.serviceWorker.controller);
 assert.equal(await page.locator('.road-bottom-nav').count(),1);
 await page.locator('[data-road-menu]').click();
 assert.equal(await page.locator('.road-app-menu').evaluate(e=>e.open),true);
 assert.equal(await page.evaluate(()=>tapCount),1);
 await page.locator('[data-road-haptics]').uncheck();
 await page.locator('[data-road-install]').click();
 assert.match(await page.locator('[data-road-install-status]').innerText(),/browser menu/);
 const count=await page.evaluate(()=>tapCount);
 await page.locator('.road-menu-close').click();
 assert.equal(await page.evaluate(()=>tapCount),count);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 const cached=await page.evaluate(async()=>{const c=await caches.open('cwd-offline-v1');return (await c.keys()).map(r=>new URL(r.url).pathname)});
 assert.deepEqual(cached,['/offline.html']);
 const manifest=await (await context.request.get('http://127.0.0.1:4193/manifest.webmanifest')).json();
 assert.equal(manifest.display,'standalone');
 for(const icon of manifest.icons)assert.equal((await context.request.get('http://127.0.0.1:4193'+icon.src)).status(),200);
 await context.setOffline(true);
 await page.goto('http://127.0.0.1:4193/my-bookings');
 assert.match(await page.locator('body').innerText(),/You're offline/);
 assert.equal(await page.evaluate(async()=>{try{await fetch('/api/customer-account');return true}catch{return false}}),false);
 await context.setOffline(false);
 await page.goto('http://127.0.0.1:4193/customer-account');
 assert.equal(await page.locator('#login-form').count(),1);
 console.log('PASS: mobile navigation, haptics toggle, install guidance, manifest/icons, service worker offline/recovery; only generic offline page cached, account API never served from cache.');
}finally{await browser.close();server.close();}
